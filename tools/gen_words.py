"""Write src/words.js: English words with their Zipf frequency (wordfreq), for spotting a video's key terms
(words said often in the video but rare in English). Words under Zipf 3.5 are left out and count as rare.

    pip install wordfreq
    python tools/gen_words.py

The word frequencies come from wordfreq (https://github.com/rspeer/wordfreq) and are under CC BY-SA 4.0; see NOTICE.
"""
import json
from pathlib import Path

from wordfreq import top_n_list, zipf_frequency

CUT = 3.5
words = {}
for w in top_n_list("en", 60000):
    z = zipf_frequency(w, "en")
    if z >= CUT:
        words[w] = round(z, 2)
# spoken forms the ranked list leaves out although they are common
for w in ("y'all", "c'mon", "ma'am", "o'clock", "ya'll", "'cause", "lil'", "goin'", "nothin'", "somethin'", "doin'",
          "talkin'", "gonna", "wanna", "gotta", "kinda", "sorta", "lemme", "gimme", "dunno", "ya", "yo", "nah", "yup"):
    z = zipf_frequency(w, "en")
    if z >= CUT:
        words[w] = round(z, 2)
out = Path(__file__).resolve().parent.parent / "src" / "words.js"
out.write_text("// Generated by tools/gen_words.py from wordfreq (CC BY-SA 4.0, see NOTICE). English Zipf frequency >= "
               f"{CUT}.\nself.LivesubWords = {json.dumps(words, separators=(',', ':'), ensure_ascii=False)};\n",
               encoding="utf-8")
print(f"{len(words)} words -> {out}")
